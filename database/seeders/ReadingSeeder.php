    /**
     * Seed the meter readings transcribed from the paper notebook.
     */
    public function run(): void
    {
        $property = Property::query()
            ->where('name', MeterSeeder::PROPERTY_NAME)
            ->firstOrFail();

        $gasMeter = $this->meter($property, MeterSeeder::GAS_METER_NAME);
        $waterMeter = $this->meter($property, MeterSeeder::WATER_METER_NAME);
        $singleZoneElectricityMeter = $this->meter($property, MeterSeeder::SINGLE_ZONE_ELECTRICITY_METER_NAME);
        $twoZoneElectricityMeter = $this->meter($property, MeterSeeder::TWO_ZONE_ELECTRICITY_METER_NAME);

        DB::transaction(function () use ($gasMeter, $waterMeter, $singleZoneElectricityMeter, $twoZoneElectricityMeter): void {
            foreach ($this->readings() as [$date, $gas, $water, $electricity, $night]) {
                $this->record($gasMeter, $date, 1, $gas);
                $this->record($waterMeter, $date, 1, $water);

                if ($electricity === null) {
                    continue;
                }

                if ($night === null) {
                    $this->record($singleZoneElectricityMeter, $date, 1, $electricity);

                    continue;
                }

                $this->record($twoZoneElectricityMeter, $date, 1, $electricity);
                $this->record($twoZoneElectricityMeter, $date, 2, $night);
            }
        });
    }

    private function meter(Property $property, string $name): Meter
    {
        return $property->meters()->where('name', $name)->sole();
    }

    private function record(Meter $meter, string $date, int $zone, ?int $value): void
    {
        if ($value === null) {
            return;
        }

        $meter->readings()->firstOrCreate(
            [
                'zone' => $zone,
                'date' => Carbon::parse($date),
            ],
            [
                'property_id' => $meter->property_id,
                'value' => $value,
            ],
        );
    }

